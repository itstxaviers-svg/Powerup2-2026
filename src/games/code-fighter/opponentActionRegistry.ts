// Compatibility view for existing action-only consumers.
export const opponentActionRegistry = Object.fromEntries(
  Object.entries(opponentPresentationRegistry).map(([id, presentation]) => [id, presentation.actions]),
) as Record<OpponentId, OpponentActionRegistry>

export function resolveOpponentActionAsset(registry: Partial<OpponentActionRegistry>, state: FighterState, warn: (message: string) => void = console.warn) {
  const requested = registry[state]
  if (requested) return requested
  warn(`Missing opponent ${state} art; using this opponent's idle art.`)
  return registry.idle ?? ''
}

export function opponentActionAsset(opponentId: OpponentId, state: FighterState) {
  return resolveOpponentActionAsset(opponentPresentationRegistry[opponentId].actions, state)
}

export function opponentVictoryResultAsset(opponentId: OpponentId) {
  return opponentPresentationRegistry[opponentId].actions.resultVictory
}

export const opponentFallbackAsset = (opponentId: OpponentId) => opponentPresentationRegistry[opponentId].actions.idle

export function opponentRuntimeAssets(opponentId: OpponentId) {
  return [...new Set(Object.values(opponentPresentationRegistry[opponentId].actions))]
}

export function preloadOpponentActions(opponentId: OpponentId) {
  if (typeof Image === 'undefined') return []
  return opponentRuntimeAssets(opponentId).map((source) => {
    const image = new Image()
    image.src = source
    return image
  })
}
