export type OpponentActionRegistry = Record<FighterState | 'resultVictory', string>
export type OpponentPresentation = {
  base?: string
  mirrorX: boolean
  mirroredStates?: readonly FighterState[]
  actions: OpponentActionRegistry
}

const actions = (
  idle: string,
  quickAttack: string,
  heavyAttack: string,
  block: string,
  counter: string,
  hitReaction: string,
  victory: string,
  tiredDefeat: string,
  resultVictory: string,
): OpponentActionRegistry => ({
  idle, quickAttack, heavyAttack, block, counter, hitReaction,
  // Enemy ultimate art is reserved for the delayed defeat result reveal.
  ultimate: heavyAttack,
  victory,
  tiredDefeat,
  resultVictory,
})

